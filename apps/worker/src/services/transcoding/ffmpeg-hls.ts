import { execFile } from 'node:child_process';
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { promisify } from 'node:util';
import type { VideoProbe } from '../ffprobe/probe.js';
import { planHlsProfiles, renderHlsMaster, type HlsProfile } from './hls-profiles.js';
import { readTranscodingBudget } from './resource-budget.js';

const execFileAsync = promisify(execFile);
const SEGMENT_NAME = /^segment_[0-9]{5,8}\.ts$/u;
const HLS_MAX_BUFFER = 64 * 1024;

export type HlsOutputFile = {
  relativePath: string;
  absolutePath: string;
  sizeBytes: bigint;
  contentType: string;
};
export type HlsEncodingResult = { profiles: HlsProfile[]; files: HlsOutputFile[] };
export type HlsRunner = (
  executable: string,
  args: string[],
  options: {
    timeout: number;
    maxBuffer: number;
    signal: AbortSignal;
    windowsHide: boolean;
  },
) => Promise<unknown>;

const runFfmpeg: HlsRunner = async (binary, args, options) => {
  await execFileAsync(binary, args, options);
};

function ensureActive(signal: AbortSignal): void {
  if (signal.aborted) throw new Error('TRANSCODING_CANCELLED');
}

/** Inspect ONLY files and relative paths generated by FFmpeg (not user-supplied names). */
async function inspectVariant(directory: string, label: string): Promise<HlsOutputFile[]> {
  const names = await readdir(directory);
  const playlist = await readFile(join(directory, 'index.m3u8'), 'utf8');
  if (!playlist.startsWith('#EXTM3U\n') || !playlist.includes('#EXT-X-ENDLIST')) {
    throw new Error('HLS_PLAYLIST_INCOMPLETE');
  }
  const entries = playlist.split(/\r?\n/u).filter((line) => line && !line.startsWith('#'));
  if (
    !entries.length ||
    entries.some((name) => !SEGMENT_NAME.test(name)) ||
    new Set(entries).size !== entries.length
  )
    throw new Error('HLS_SEGMENTS_INVALID');
  if (
    names.length !== entries.length + 1 ||
    names.some((name) => name !== 'index.m3u8' && !entries.includes(name))
  ) {
    throw new Error('HLS_OUTPUT_UNEXPECTED_FILE');
  }
  const files: HlsOutputFile[] = [];
  for (const name of entries) {
    const absolutePath = join(directory, name);
    const info = await stat(absolutePath);
    if (!info.isFile() || info.size < 1) throw new Error('HLS_SEGMENT_INVALID');
    files.push({
      relativePath: `${label}/${name}`,
      absolutePath,
      sizeBytes: BigInt(info.size),
      contentType: 'video/mp2t',
    });
  }
  const playlistStat = await stat(join(directory, 'index.m3u8'));
  if (!playlistStat.isFile() || playlistStat.size < 1) throw new Error('HLS_PLAYLIST_INVALID');
  files.push({
    relativePath: `${label}/index.m3u8`,
    absolutePath: join(directory, 'index.m3u8'),
    sizeBytes: BigInt(playlistStat.size),
    contentType: 'application/vnd.apple.mpegurl',
  });
  return files;
}

/**
 * Encode VOD renditions sequentially (bounded CPU usage). FFmpeg runs without a shell.
 * Complete variant playlists and file sizes are verified before any S3 write.
 */
export async function encodeHlsVideo(
  sourcePath: string,
  outputDirectory: string,
  probe: VideoProbe,
  signal: AbortSignal,
  options: { runner?: HlsRunner; binary?: string } = {},
): Promise<HlsEncodingResult> {
  const profiles = planHlsProfiles(probe);
  const budget = readTranscodingBudget();
  const runner = options.runner ?? runFfmpeg;
  const binary = options.binary ?? process.env.FFMPEG_PATH ?? 'ffmpeg';
  const files: HlsOutputFile[] = [];
  for (const profile of profiles) {
    ensureActive(signal);
    const dir = join(outputDirectory, profile.label);
    await mkdir(dir, { recursive: false });
    const args = [
      '-hide_banner',
      '-nostdin',
      '-loglevel',
      'error',
      '-y',
      '-i',
      sourcePath,
      '-map',
      '0:v:0',
      ...(probe.hasAudio ? ['-map', '0:a:0'] : []),
      '-filter_threads',
      String(budget.ffmpegThreads),
      '-vf',
      `scale=${profile.width}:${profile.height}:flags=lanczos,setsar=1`,
      '-c:v',
      'libx264',
      '-preset',
      'veryfast',
      '-pix_fmt',
      'yuv420p',
      '-threads',
      String(budget.ffmpegThreads),
      '-b:v',
      String(profile.videoBitrate),
      '-maxrate',
      String(Math.round(profile.videoBitrate * 1.2)),
      '-bufsize',
      String(profile.videoBitrate * 2),
      '-sc_threshold',
      '0',
      '-force_key_frames',
      'expr:gte(t,n_forced*4)',
      ...(probe.hasAudio
        ? ['-c:a', 'aac', '-b:a', String(profile.audioBitrate), '-ac', '2']
        : ['-an']),
      '-f',
      'hls',
      '-hls_time',
      '4',
      '-hls_playlist_type',
      'vod',
      '-hls_flags',
      'independent_segments',
      '-hls_segment_type',
      'mpegts',
      '-hls_segment_filename',
      join(dir, 'segment_%05d.ts'),
      join(dir, 'index.m3u8'),
    ];
    try {
      await runner(binary, args, {
        timeout: budget.ffmpegProfileTimeoutMs,
        maxBuffer: HLS_MAX_BUFFER,
        signal,
        windowsHide: true,
      });
    } catch (error) {
      if (signal.aborted) throw new Error('TRANSCODING_CANCELLED', { cause: error });
      throw new Error('HLS_FFMPEG_FAILED', { cause: error });
    }
    files.push(...(await inspectVariant(dir, profile.label)));
  }
  ensureActive(signal);
  const masterPath = join(outputDirectory, 'master.m3u8');
  await writeFile(masterPath, renderHlsMaster(profiles), {
    encoding: 'utf8',
    flag: 'wx',
    mode: 0o600,
  });
  const masterStat = await stat(masterPath);
  files.push({
    relativePath: 'master.m3u8',
    absolutePath: masterPath,
    sizeBytes: BigInt(masterStat.size),
    contentType: 'application/vnd.apple.mpegurl',
  });
  return { profiles, files };
}
