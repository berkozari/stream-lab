import { spawnSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { expect, test, type Page } from '@playwright/test';

const repositoryRoot = fileURLToPath(new URL('../../../../', import.meta.url));
const password = 'StreamLabE2E-StrongPassword-2026!';
const displayName = 'StreamLab E2E';
let accountEmail: string | undefined;

function nextAccount(): string {
  accountEmail = `streamlab-e2e-${randomUUID()}@example.invalid`;
  return accountEmail;
}

async function register(page: Page, email: string): Promise<void> {
  await page.goto('/register');
  await page.getByRole('textbox', { name: 'Görünen ad' }).fill(displayName);
  await page.getByRole('textbox', { name: 'E-posta' }).fill(email);
  await page.getByLabel('Şifre', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Kayıt ol' }).click();
  await expect(page.getByRole('heading', { name: 'İçerik yönetimi' })).toBeVisible();
}

async function login(page: Page, email: string, pass = password): Promise<void> {
  await page.goto('/login');
  await page.getByRole('textbox', { name: 'E-posta' }).fill(email);
  await page.getByLabel('Şifre', { exact: true }).fill(pass);
  await page.getByRole('button', { name: 'Giriş yap' }).click();
}

// Only accounts generated by these E2E tests are eligible for deletion.
test.afterEach(() => {
  if (!accountEmail) return;
  const email = accountEmail;
  accountEmail = undefined;
  const result = spawnSync(
    'pnpm',
    ['--filter', '@streamlab/api', 'exec', 'tsx', 'scripts/auth-e2e-cleanup.ts', email],
    { cwd: repositoryRoot, encoding: 'utf8', timeout: 30_000 },
  );
  if (result.status !== 0) {
    throw new Error(
      `E2E test-user cleanup failed for ${email}: ${result.stderr || result.stdout || String(result.error)}`,
    );
  }
});

test('anonymous user keeps safe returnTo through register, reload and logout', async ({ page }) => {
  const email = nextAccount();
  await page.goto('/creator?tab=uploads');
  await expect(page).toHaveURL(/\/login\?returnTo=/u);
  await page.getByRole('link', { name: 'Kayıt ol' }).click();
  await expect(page).toHaveURL(/\/register\?returnTo=/u);

  await page.getByRole('textbox', { name: 'Görünen ad' }).fill(displayName);
  await page.getByRole('textbox', { name: 'E-posta' }).fill(email);
  await page.getByLabel('Şifre', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Kayıt ol' }).click();
  await expect(page).toHaveURL(/\/creator\?tab=uploads$/u);
  await expect(page.getByRole('heading', { name: 'İçerik yönetimi' })).toBeVisible();

  const refreshCookie = (await page.context().cookies()).find((cookie) => {
    return cookie.name === 'streamlab_refresh';
  });
  expect(refreshCookie?.httpOnly).toBe(true);
  expect(refreshCookie?.path).toBe('/api/v1/auth');
  const storedTokenKeys = await page.evaluate(() => {
    return [...Object.keys(localStorage), ...Object.keys(sessionStorage)].filter((key) => {
      return /(?:access|refresh).*token/iu.test(key);
    });
  });
  expect(storedTokenKeys).toEqual([]);

  await page.reload();
  await expect(page.getByRole('heading', { name: 'İçerik yönetimi' })).toBeVisible();
  await page.getByRole('button', { name: 'Çıkış' }).click();
  await expect(page).toHaveURL(/\/login\?returnTo=/u);
  await page.goto('/creator');
  await expect(page).toHaveURL(/\/login/u);
});

test('invalid register data shows field errors without sending a POST', async ({ page }) => {
  let registerRequests = 0;
  page.on('request', (request) => {
    if (request.method() === 'POST' && request.url().endsWith('/api/v1/auth/register')) {
      registerRequests += 1;
    }
  });
  await page.goto('/register');
  await page.getByRole('button', { name: 'Kayıt ol' }).click();
  await expect(page.getByText('Görünen adını gir.')).toBeVisible();
  await expect(page.getByText('Geçerli bir e-posta adresi gir.')).toBeVisible();
  await expect(page.getByText('Şifre 12–128 karakter arasında olmalı.')).toBeVisible();
  expect(registerRequests).toBe(0);
});

test('wrong password is rejected without revealing account existence', async ({ page }) => {
  const email = nextAccount();
  await register(page, email);
  await page.getByRole('button', { name: 'Çıkış' }).click();
  await expect(page).toHaveURL(/\/login/u);
  await login(page, email, 'not-the-right-password');
  await expect(page.getByRole('alert')).toContainText('E-posta veya şifre hatalı.');
  await login(page, email);
  await expect(page.getByRole('heading', { name: 'İçerik yönetimi' })).toBeVisible();
});

test('logout revokes only the current browser session', async ({ page, browser }) => {
  const email = nextAccount();
  await register(page, email);

  const otherContext = await browser.newContext();
  try {
    const otherPage = await otherContext.newPage();
    await login(otherPage, email);
    await expect(otherPage.getByRole('heading', { name: 'İçerik yönetimi' })).toBeVisible();

    await page.getByRole('button', { name: 'Çıkış' }).click();
    await expect(page).toHaveURL(/\/login/u);

    // A reload forces a real HttpOnly-cookie bootstrap in the independent context.
    await otherPage.reload();
    await expect(otherPage.getByRole('heading', { name: 'İçerik yönetimi' })).toBeVisible();
  } finally {
    await otherContext.close();
  }
});
