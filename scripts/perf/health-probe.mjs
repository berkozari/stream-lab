#!/usr/bin/env node
import { parseHealthProbeArgs, sampleHealthEndpoint } from '../lib/stream-009-6-perf.mjs';

if (process.argv.includes('--help')) {
  console.log(`STREAM-009.6 local, read-only health sampler
Usage: node scripts/perf/health-probe.mjs [--url http://127.0.0.1:4000/api/v1/health] [--requests 40] [--concurrency 2] [--timeout-ms 1500] [--p95-ms 500] [--max-errors 0]
Only localhost/127.0.0.1/[::1] /api/v1/health is allowed. Requests <=200; concurrency <=8; GET only.
No traffic is generated by --help, --plan, or the normal offline test suite.`);
} else {
  try {
    const config = parseHealthProbeArgs(process.argv.slice(2));
    if (process.argv.includes('--plan'))
      throw new Error('Use --help to preview; --plan is not supported');
    console.log(
      `[STREAM-009.6] Local health sample: ${config.requests} GET requests, concurrency ${config.concurrency}, timeout ${config.timeoutMs}ms`,
    );
    const report = await sampleHealthEndpoint(config);
    console.log(
      `[STREAM-009.6] ${report.passed ? 'PASS' : 'FAIL'}: ${report.successes}/${report.sent} valid responses, ${report.errors} errors; p50=${report.p50Ms?.toFixed(1) ?? 'n/a'}ms, p95=${report.p95Ms?.toFixed(1) ?? 'n/a'}ms; elapsed=${report.elapsedMs.toFixed(1)}ms`,
    );
    if (!report.passed) process.exitCode = 1;
  } catch (error) {
    console.error(`[STREAM-009.6] ${error instanceof Error ? error.message : 'Invalid arguments'}`);
    process.exitCode = 2;
  }
}
